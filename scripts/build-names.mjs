// Builds src/seal/names-data.ts, the name-list layer: common US first names (US baby names, 1940-2008, from
// github.com/hadley/data-baby-names, SSA data) and surnames (2010 US Census, www2.census.gov/topics/genealogy/
// 2010surnames). Names that are also ordinary English words (will, grace, hunter, brown) are marked ambiguous,
// so a lower-case "will" is never held as a name.
//   node scripts/build-names.mjs <baby-names.csv> <Names_2010Census.csv>
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

const wordlist = createRequire(import.meta.url)('wordlist-english');

const [babyPath, censusPath] = process.argv.slice(2);
if (!babyPath || !censusPath) throw new Error('usage: node scripts/build-names.mjs <baby-names.csv> <Names_2010Census.csv>');

// Common English words: the 10, 20 and 35 frequency tiers of SCOWL (wordlist-english).
const english = new Set([...wordlist['english/10'], ...wordlist['english/20'], ...wordlist['english/35']]);
const first = new Map();
for (const line of (await readFile(babyPath, 'utf8')).split('\n').slice(1)) {
  const [year, name, percent] = line.replace(/"/g, '').split(',');
  if (!name || Number(year) < 1940) continue;
  const p = Number(percent);
  if (p >= 0.0002) first.set(name.toLowerCase(), Math.max(first.get(name.toLowerCase()) ?? 0, p));
}
const last = [];
for (const line of (await readFile(censusPath, 'utf8')).split('\n').slice(1)) {
  const [name, rank] = line.split(',');
  if (name && Number(rank) <= 6000 && /^[A-Z]+$/.test(name)) last.push(name.toLowerCase());
}
const firstNames = [...first.keys()].filter((n) => n.length >= 3).sort();
const lastNames = last.filter((n) => n.length >= 3).sort();
const ambiguous = [...new Set([...firstNames, ...lastNames])].filter((n) => english.has(n)).sort();
const out = `// Generated by scripts/build-names.mjs from public US data. Do not edit by hand.
// ${String(firstNames.length)} first names, ${String(lastNames.length)} surnames, ${String(ambiguous.length)} that are also English words.
export const FIRST_NAMES = ${JSON.stringify(firstNames.join(' '))};
export const LAST_NAMES = ${JSON.stringify(lastNames.join(' '))};
export const AMBIGUOUS = ${JSON.stringify(ambiguous.join(' '))};
`;
await writeFile('src/seal/names-data.ts', out);
console.log(`names: ${String(firstNames.length)} first, ${String(lastNames.length)} last, ${String(ambiguous.length)} ambiguous`);
